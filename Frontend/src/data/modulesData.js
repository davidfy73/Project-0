// Helper untuk mengambil modul berdasarkan ID slug
export function getModuleById(slug) {
  return MODULES_DATA.find((m) => m.id === slug) || null;
}

// Helper untuk menghitung navigasi antar section dan modul
export function getNavigation(currentSlug, currentSectionId) {
  const currentModIndex = MODULES_DATA.findIndex((m) => m.id === currentSlug);
  if (currentModIndex === -1) return null;

  const currentMod = MODULES_DATA[currentModIndex];
  const sectionNum = parseInt(currentSectionId, 10);
  const currentSecIndex = currentMod.sections.findIndex((s) => s.id === sectionNum);
  
  if (currentSecIndex === -1) return null;

  const totalSections = currentMod.sections.length;

  // Hitung Previous
  let prev = null;
  if (currentSecIndex > 0) {
    prev = {
      slug: currentMod.id,
      section: currentMod.sections[currentSecIndex - 1].id,
      path: `/module/${currentMod.id}/${currentMod.sections[currentSecIndex - 1].id}`,
    };
  } else if (currentModIndex > 0) {
    const prevMod = MODULES_DATA[currentModIndex - 1];
    const prevModLastSec = prevMod.sections[prevMod.sections.length - 1];
    prev = {
      slug: prevMod.id,
      section: prevModLastSec.id,
      path: `/module/${prevMod.id}/${prevModLastSec.id}`,
    };
  }

  // Hitung Next
  let next = null;
  if (currentSecIndex < totalSections - 1) {
    next = {
      slug: currentMod.id,
      section: currentMod.sections[currentSecIndex + 1].id,
      path: `/module/${currentMod.id}/${currentMod.sections[currentSecIndex + 1].id}`,
      isEnd: false,
    };
  } else if (currentModIndex < MODULES_DATA.length - 1) {
    const nextMod = MODULES_DATA[currentModIndex + 1];
    const nextModFirstSec = nextMod.sections[0];
    next = {
      slug: nextMod.id,
      section: nextModFirstSec.id,
      path: `/module/${nextMod.id}/${nextModFirstSec.id}`,
      isEnd: false,
    };
  } else {
    next = {
      slug: null,
      section: null,
      path: '/modules',
      isEnd: true,
    };
  }

  return {
    module: currentMod,
    section: currentMod.sections[currentSecIndex],
    currentSectionNum: sectionNum,
    totalSections,
    isFirst: currentModIndex === 0 && currentSecIndex === 0,
    isLast: currentModIndex === MODULES_DATA.length - 1 && currentSecIndex === totalSections - 1,
    prev,
    next,
  };
}
